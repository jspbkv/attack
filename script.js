function triggerDownload(fileId) {
    if (state.user.isGuest) {
        openRestrictedModal();
        return;
    }
    const file = downloadFiles.find(f => f.id === fileId);
    if (!file || !file.url) {
        showToast(i18n[state.lang].downloadUnavailable, 'error');
        return;
    }

    let downloadUrl;
    try {
        downloadUrl = new URL(file.url, window.location.href);
    } catch {
        showToast(i18n[state.lang].downloadUnavailable, 'error');
        return;
    }
    if (downloadUrl.protocol !== 'https:') {
        showToast(i18n[state.lang].downloadUnavailable, 'error');
        return;
    }

    const link = document.createElement('a');
    link.href = downloadUrl.href;
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    link.click();

    state.user.downloads += 1;
    saveState();
    renderProfile();
    showToast(i18n[state.lang].downloadSuccess + ` (${file.title})`, 'success');
}

