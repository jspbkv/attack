async function updateServerStatus() {
    const card = document.getElementById('server-card');
    const statusText = document.getElementById('server-status-text');
    const playerCount = document.getElementById('server-player-count');
    const updated = document.getElementById('server-updated');
    if (!card || !statusText || !playerCount || !updated) return;

    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 10000);
    card.dataset.status = 'loading';
    renderServerStatusLabels();

    try {
        const response = await fetch('https://api.mcsrvstat.us/bedrock/3/play.breadixpe.net:19132', {
            signal: controller.signal
        });
        if (!response.ok) {
            throw new Error(`Server status request failed: ${response.status}`);
        }

        const server = await response.json();
        if (typeof server.online !== 'boolean') {
            throw new Error('Server status response is missing its online state.');
        }

        card.dataset.status = server.online ? 'online' : 'offline';

        const onlinePlayers = server.online && Number.isFinite(server.players?.online)
            ? server.players.online
            : 0;
        const maxPlayers = Number.isFinite(server.players?.max) ? server.players.max : null;
        playerCount.textContent = maxPlayers === null
            ? String(onlinePlayers)
            : `${onlinePlayers} / ${maxPlayers}`;
        updated.dataset.checkedAt = String(Date.now());
        renderServerStatusLabels();
    } catch (error) {
        console.error('Unable to load Minecraft server status:', error);
        card.dataset.status = 'error';
        playerCount.textContent = '—';
        delete updated.dataset.checkedAt;
        renderServerStatusLabels();
    } finally {
        clearTimeout(timeout);
    }
}

async function copyServerValue(value, button) {
    try {
        if (navigator.clipboard?.writeText && window.isSecureContext) {
            try {
                await navigator.clipboard.writeText(value);
            } catch {
                copyTextWithFallback(value);
            }
        } else {
            copyTextWithFallback(value);
        }

        const label = button.querySelector('[data-i18n="copyButton"]');
        if (label) {
            label.textContent = i18n[state.lang].copySuccess;
            setTimeout(() => {
                label.textContent = i18n[state.lang].copyButton;
            }, 1600);
        }
    } catch (error) {
        console.error('Unable to copy server address:', error);
        showToast(i18n[state.lang].copyFailed, 'info');
    }
}

function copyTextWithFallback(value) {
    const input = document.createElement('textarea');
    input.value = value;
    input.setAttribute('readonly', '');
    input.style.position = 'fixed';
    input.style.opacity = '0';
    document.body.appendChild(input);

    try {
        input.select();
        if (!document.execCommand('copy')) {
            throw new Error('The browser could not write to the clipboard.');
        }
    } finally {
        input.remove();
    }
}

