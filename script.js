function getCleanSupabaseUrl(rawUrl) {
    if (!rawUrl) return '';
    let clean = rawUrl.trim();
    clean = clean.replace(/\/rest\/v1\/?$/, '');
    clean = clean.replace(/\/$/, '');
    return clean;
}

function initSupabase() {
    const cleanUrl = getCleanSupabaseUrl(supabaseConfig.url);
    const key = (supabaseConfig.key || '').trim();

    if (window.supabase && cleanUrl && key) {
        try {
            supabaseClient = window.supabase.createClient(cleanUrl, key, {
                global: {
                    headers: {
                        'apikey': key,
                        'Authorization': 'Bearer ' + key
                    }
                }
            });
            console.log("Supabase Client initialized with URL:", cleanUrl);

            supabaseClient.auth.getSession().then(({ data: { session } }) => {
                if (session) {
                    syncSupabaseUser(session.user);
                }
            });

            supabaseClient.auth.onAuthStateChange((_event, session) => {
                if (session) {
                    syncSupabaseUser(session.user);
                }
            });

            subscribeRealtimeChat();
        } catch (e) {
            console.warn("Supabase init error:", e);
        }
    }
}

