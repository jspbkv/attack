function updateCarouselTransform() {
    const track = document.getElementById('carousel-track');
    if (!track || track.children.length === 0) return;

    const card = track.children[0];
    const cardWidth = card.getBoundingClientRect().width + 20;
    track.style.transform = `translateX(-${state.carouselIndex * cardWidth}px)`;

    document.querySelectorAll('.dot').forEach((dot, idx) => {
        dot.classList.toggle('active', idx === state.carouselIndex);
    });
}

function setCarouselIndex(idx) {
    state.carouselIndex = idx;
    updateCarouselTransform();
}

function initCarouselControls() {
    const prevBtn = document.getElementById('carousel-prev');
    const nextBtn = document.getElementById('carousel-next');

    if (prevBtn) {
        prevBtn.addEventListener('click', () => {
            state.carouselIndex = (state.carouselIndex - 1 + carouselCardsData.length) % carouselCardsData.length;
            updateCarouselTransform();
        });
    }

    if (nextBtn) {
        nextBtn.addEventListener('click', () => {
            state.carouselIndex = (state.carouselIndex + 1) % carouselCardsData.length;
            updateCarouselTransform();
        });
    }

    setInterval(() => {
        if (state.activeTab === 'home') {
            state.carouselIndex = (state.carouselIndex + 1) % carouselCardsData.length;
            updateCarouselTransform();
        }
    }, 6000);
}

